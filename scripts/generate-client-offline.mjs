/**
 * Generate the Prisma Client without downloading native engine binaries.
 *
 * `prisma generate` fetches a platform-specific Rust query engine from
 * binaries.prisma.sh before it will run. In sandboxed, air-gapped, or
 * download-restricted environments that host is unreachable, which makes local
 * development impossible — even though the PostgreSQL query engine shipped as
 * WebAssembly inside the @prisma/client npm package runs the same queries.
 *
 * This script drives Prisma's own generator in-process and points it at a stub
 * engine file so the "copy engine" step succeeds without a network fetch. The
 * generated client is identical to the CLI's output; at runtime the app uses
 * the WebAssembly engine through a driver adapter (see server/db.ts), so the
 * stub is never loaded.
 *
 * npm's own `prisma generate` (used by the Vercel build) is untouched.
 *
 * Usage: npm run db:generate:offline
 */
import fs from 'node:fs';
import path from 'node:path';
import internals from '@prisma/internals';

const { getGenerators } = internals;

const PLATFORM_FALLBACK = 'debian-openssl-3.0.x';

async function resolveBinaryTarget() {
  try {
    const getPlatform = await import('@prisma/get-platform');
    return await getPlatform.getBinaryTargetForCurrentPlatform();
  } catch {
    return PLATFORM_FALLBACK;
  }
}

/**
 * Prisma insists on resolving (and then copying) a native engine path. Create
 * an empty stand-in when the real binary is unavailable so generation proceeds.
 */
function ensureStubEngine(binaryTarget) {
  const engineDir = path.resolve(process.cwd(), 'node_modules', '@prisma', 'engines');
  fs.mkdirSync(engineDir, { recursive: true });

  const stubPath = path.join(engineDir, `libquery_engine-${binaryTarget}.so.node`);
  if (!fs.existsSync(stubPath)) {
    fs.writeFileSync(stubPath, '');
  }
  return stubPath;
}

/**
 * Prisma's generated client resolves its engine through the `#wasm-engine-loader`
 * import map, whose loaders rely on bundler features (`import('./*.wasm?module')`
 * and `import('./*.wasm')`) that only Cloudflare/edge runtimes implement. Node
 * therefore reports "loaded wasm module was unexpectedly undefined".
 *
 * Register a Node condition in the import map that compiles the same
 * WebAssembly engine from disk. This is additive: every existing condition
 * (edge-light, workerd, worker, default) keeps its original target.
 */
function linkWasmEngineLoader(outputDir) {
  const packageJsonPath = path.join(outputDir, 'package.json');
  const loaderPath = path.join(outputDir, 'wasm-node-loader.mjs');

  const loaderSource = `// Generated by scripts/generate-client-offline.mjs
// Loads the PostgreSQL query engine that ships as WebAssembly inside
// @prisma/client, so Prisma Client runs in Node without a native engine binary.
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const wasmPath = require.resolve('@prisma/client/runtime/query_engine_bg.postgresql.wasm');
const bytes = fs.readFileSync(wasmPath);

export default { default: new WebAssembly.Module(bytes) };
`;

  fs.writeFileSync(loaderPath, loaderSource);

  let pkg = {};
  if (fs.existsSync(packageJsonPath)) {
    try {
      pkg = JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'));
    } catch {
      pkg = {};
    }
  }

  const existing = pkg.imports?.['#wasm-engine-loader'];

  pkg.imports = {
    ...(pkg.imports || {}),
    '#wasm-engine-loader':
      typeof existing === 'object' && existing !== null
        ? { node: './wasm-node-loader.mjs', ...existing }
        : { node: './wasm-node-loader.mjs', default: existing ?? './wasm-node-loader.mjs' },
  };

  fs.writeFileSync(packageJsonPath, `${JSON.stringify(pkg, null, 2)}\n`);
  console.log('[db:generate:offline] registered Node WASM engine loader');
}

/**
 * Locate the directory Prisma writes the generated client into. The generator
 * reports the @prisma/client package as its output, while the actual client is
 * emitted into node_modules/.prisma/client, so prefer whichever directory holds
 * the freshly generated runtime entry point.
 */
function resolveClientOutputDir(generator) {
  const candidates = [
    path.resolve(process.cwd(), 'node_modules', '.prisma', 'client'),
    generator.options?.generator?.output?.value,
  ].filter(Boolean);

  for (const candidate of candidates) {
    if (fs.existsSync(path.join(candidate, 'wasm.js'))) {
      return candidate;
    }
  }

  return candidates[0];
}

async function main() {
  const schemaPath = path.resolve(process.cwd(), 'prisma', 'schema.prisma');
  const binaryTarget = await resolveBinaryTarget();
  const stubEnginePath = ensureStubEngine(binaryTarget);

  const generators = await getGenerators({
    schemaPath,
    printDownloadProgress: false,
    // Never reach out to binaries.prisma.sh.
    skipDownload: true,
    binaryPathsOverride: {
      libqueryEngine: stubEnginePath,
    },
  });

  if (generators.length === 0) {
    throw new Error('No generators found in prisma/schema.prisma');
  }

  try {
    for (const generator of generators) {
      const name = generator.options?.generator?.name ?? 'generator';
      const outputDir = resolveClientOutputDir(generator);

      await generator.generate();
      console.log(
        `[db:generate:offline] generated "${name}" client for ${binaryTarget} (no engine download)`
      );

      linkWasmEngineLoader(outputDir);
    }
  } finally {
    await Promise.all(generators.map((generator) => generator.stop()));
  }
}

main().catch((error) => {
  console.error('[db:generate:offline] failed:', error);
  process.exit(1);
});

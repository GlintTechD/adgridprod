export const TIER_RANK: Record<PlanTier, number> = {
  starter: 1,
  professional: 2,
  enterprise: 3,
  custom: 4,
};

export function getTierName(tier: PlanTier): string {
  switch (tier) {
    case 'starter':
      return 'Starter';
    case 'professional':
      return 'Professional';
    case 'enterprise':
      return 'Enterprise';
    case 'custom':
      return 'Custom Enterprise';
    default:
      return 'Starter';
  }
}
